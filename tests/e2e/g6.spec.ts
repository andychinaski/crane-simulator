import { expect, test, type Page } from '@playwright/test'
import { canvas, chooseDemo, chooseManual, lowerRopeToLimit, modeDialog, setSlider, skipOnboarding, status, waitForCrane } from './controls'

const card = (page: Page) => page.locator('.guide-card')
const next = (page: Page) => card(page).getByRole('button', { name: 'Далее' })
const choose = (page: Page) => page.getByRole('button', { name: 'Выбрать режим' })
const reset = (page: Page) => page.getByRole('button', { name: 'Сбросить сценарий' })
const confirmReset = (page: Page) => modeDialog(page).getByRole('button', { name: 'Сбросить и продолжить' })
const cancel = (page: Page) => modeDialog(page).getByRole('button', { name: 'Отмена' })

async function capture(page: Page, name: string, fullPage = false) {
  if (process.env.CAPTURE_G6 === '1') {
    await page.screenshot({ path: `evidence/G6/${name}.png`, fullPage })
  }
}

test('G6 checks all ten guided steps, transient motion, rollback and transferred settings', async ({ page }) => {
  test.setTimeout(90_000)
  await page.setViewportSize({ width: 1672, height: 941 })
  await skipOnboarding(page)
  await expect(modeDialog(page).getByRole('checkbox')).toBeChecked()
  await chooseManual(page, true)
  await expect(card(page)).toContainText('Шаг 1 из 10')
  await expect(next(page)).toBeDisabled()
  await expect(page.locator('#ropeLength')).toBeFocused()
  await setSlider(page, 'movementSpeed', 25)
  await setSlider(page, 'ropeLength', 5.1)
  await expect(status(page)).toHaveAttribute('data-moving', 'true')
  await expect(next(page)).toBeDisabled()
  await expect(next(page)).toBeEnabled({ timeout: 15_000 })
  await next(page).click()
  await setSlider(page, 'movementSpeed', 100)

  async function finishStep(step: number, id: string, target: number) {
    await expect(card(page)).toContainText(`Шаг ${step} из 10`)
    await setSlider(page, id, target)
    await expect(next(page)).toBeEnabled({ timeout: 15_000 })
    await next(page).click()
  }

  await finishStep(2, 'gripperOpen', 0)
  await finishStep(3, 'ropeLength', 3.6)
  await expect(card(page)).toContainText('Шаг 4 из 10')
  await setSlider(page, 'platformYaw', 54)
  await expect(card(page)).toContainText('✓ Выполнено')
  await setSlider(page, 'platformYaw', 49)
  await expect(next(page)).toBeDisabled()
  await expect(card(page)).toContainText('Верни значение «Поворот платформы» к 54°')
  await waitForCrane(page)
  await capture(page, 'guided-rollback-1672x941')
  await finishStep(4, 'platformYaw', 54)
  await setSlider(page, 'platformYaw', 50)
  await waitForCrane(page)
  await setSlider(page, 'boomPitch', 28)
  await waitForCrane(page)
  await expect(next(page)).toBeDisabled()
  await expect(card(page)).toContainText('Верни значение «Поворот платформы» к 54°')
  await setSlider(page, 'platformYaw', 54)
  await finishStep(5, 'boomPitch', 28)
  await finishStep(6, 'boomLength', 7.1)
  await finishStep(7, 'gripperYaw', 0)
  await expect(next(page)).toBeDisabled()
  const limit = await lowerRopeToLimit(page)
  expect(limit).toBeGreaterThan(4.1)
  expect(limit).toBeLessThan(4.2)
  await expect(next(page)).toBeEnabled()
  await next(page).click()
  await finishStep(9, 'gripperOpen', 80)
  await finishStep(10, 'ropeLength', 3)
  await expect(card(page)).toContainText('Ручной цикл завершён')
  await expect(page.locator('#cargo-status')).toHaveAttribute('data-state', 'PLACED')
  await capture(page, 'guided-delivered-1672x941')
})

test('G6 preserves the current scenario on cancellation and keeps both resets independent', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await skipOnboarding(page)
  await chooseManual(page, true)
  await setSlider(page, 'movementSpeed', 100)
  await setSlider(page, 'cameraZoom', 115)
  await setSlider(page, 'ropeLength', 5.1)
  await expect(next(page)).toBeEnabled()
  await next(page).click()
  await setSlider(page, 'gripperOpen', 0)
  await expect(next(page)).toBeEnabled()
  await choose(page).click()
  await modeDialog(page).getByRole('button', { name: 'Демонстрация' }).click()
  await expect(confirmReset(page)).toBeVisible()
  await cancel(page).click()
  await expect(modeDialog(page)).toHaveAccessibleName('Выбрать режим')
  await page.keyboard.press('Escape')
  await expect(modeDialog(page)).toBeHidden()
  await expect(card(page)).toContainText('Шаг 2 из 10')
  await expect(page.locator('#cargo-status')).toHaveAttribute('data-state', 'ATTACHED')
  await page.getByRole('button', { name: 'Сбросить вид' }).click()
  await expect(page.locator('#cameraZoom')).toHaveValue('100')
  await expect(next(page)).toBeEnabled()
  await setSlider(page, 'cameraZoom', 115)
  await reset(page).click()
  await cancel(page).click()
  await expect(modeDialog(page)).toBeHidden()
  await expect(page.locator('#cargo-status')).toHaveAttribute('data-state', 'ATTACHED')
  await reset(page).click()
  await confirmReset(page).click()
  await expect(page.locator('#cargo-status')).toHaveAttribute('data-state', 'GROUND')
  await expect(page.locator('#cameraZoom')).toHaveValue('115')
  await expect(page.locator('#movementSpeed')).toHaveValue('100')
  await expect(page.locator('#ropeLength')).toHaveValue('3.2')
  await expect(card(page)).toContainText('Шаг 1 из 10')
  await expect(next(page)).toBeDisabled()
  await setSlider(page, 'ropeLength', 5.1)
  await expect(next(page)).toBeEnabled()
  await card(page).getByRole('button', { name: 'Выйти из подсказок' }).click()
  await expect(card(page)).toHaveCount(0)
  await expect(page.locator('#cargo-hint')).toHaveText('Готов к захвату')
  await expect(page.locator('#ropeLength')).toHaveValue('5.1')
})

test('G6 lays out the mode selector and guided card across desktop and mobile sizes', async ({ page }) => {
  test.setTimeout(90_000)
  const sizes = [{ width: 1672, height: 941 }, { width: 1440, height: 900 }, { width: 1280, height: 720 },
    { width: 390, height: 844 }]
  await page.setViewportSize(sizes[0])
  await skipOnboarding(page)
  await expect(canvas(page)).toBeVisible()
  for (const size of sizes) {
    await page.setViewportSize(size)
    await expect(modeDialog(page)).toBeInViewport({ ratio: 1 })
    await expect(modeDialog(page).getByRole('checkbox')).toBeInViewport({ ratio: 1 })
    await capture(page, `mode-${size.width}x${size.height}`)
  }
  await page.setViewportSize(sizes[0])
  await chooseManual(page, true)
  await expect(page.locator('.crane-panel #cargo-status')).toBeVisible()
  await expect(page.locator('.viewport #cargo-status')).toHaveCount(0)
  await expect(page.locator('.crane-panel .demo, .crane-panel .stop')).toHaveCount(0)
  for (const size of sizes) {
    await page.setViewportSize(size)
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(size.width)
    const controls = (await page.locator('.crane-sliders').boundingBox())!
    const guide = (await card(page).boundingBox())!
    expect(guide.y).toBeGreaterThan(controls.y + controls.height)
    if (size.width > 390) await expect(card(page)).toBeInViewport({ ratio: 1 })
    await capture(page, `guided-active-${size.width}x${size.height}`, size.width === 390)
  }
  await setSlider(page, 'ropeLength', 5.1)
  await expect(next(page)).toBeEnabled()
  await next(page).scrollIntoViewIfNeeded()
  await expect(next(page)).toBeInViewport({ ratio: 1 })
  await page.setViewportSize(sizes[0])
  await expect(card(page)).toBeInViewport({ ratio: 1 })
  await capture(page, 'guided-complete-1672x941')
  await page.setViewportSize(sizes[2])
  await card(page).getByRole('button', { name: 'Выйти из подсказок' }).click()
  await capture(page, 'manual-free-1280x720')
})

test('G6 starts demo from initial choice and can repeat it from the scene toolbar', async ({ page }) => {
  test.setTimeout(60_000)
  await page.setViewportSize({ width: 1672, height: 941 })
  await skipOnboarding(page)
  await chooseDemo(page)
  await expect(modeDialog(page)).toBeHidden()
  await expect(page.locator('.viewport').getByRole('button', { name: 'Стоп' })).toBeEnabled()
  await expect(status(page)).toHaveAttribute('data-demo', 'transfer', { timeout: 20_000 })
  await capture(page, 'demo-1672x941')
  await expect(status(page)).toHaveAttribute('data-demo', 'complete', { timeout: 20_000 })
  await expect(page.locator('#cargo-status')).toHaveAttribute('data-state', 'PLACED')
  await page.getByRole('button', { name: 'Повторить демонстрацию' }).click()
  await confirmReset(page).click()
  await expect(status(page)).toHaveAttribute('data-demo', 'reset')
  await expect(page.locator('#cargo-status')).toHaveAttribute('data-state', 'GROUND')
})
