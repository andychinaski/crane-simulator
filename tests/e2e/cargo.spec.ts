import { expect, test, type Page } from '@playwright/test'
import { canvas, lowerRopeToLimit, setSlider, status, waitForCrane } from './controls'

const cargoState = (page: Page) => page.locator('#cargo-status')
const cargoHint = (page: Page) => page.locator('#cargo-hint')

async function capture(page: Page, name: string) {
  if (process.env.CAPTURE_G3 === '1') await page.screenshot({ path: `evidence/G3/${name}.png` })
}

test.beforeEach(async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('/')
  await expect(canvas(page)).toBeVisible()
  await setSlider(page, 'movementSpeed', 100)
})

test('G3 manually captures, lifts, transports, lands and detaches the crate in the zone', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
  await expect(cargoState(page)).toHaveText('Свободен')
  await setSlider(page, 'gripperOpen', 0)
  await expect(cargoHint(page)).toHaveText('Совместите захват с ручкой по высоте')
  await expect(cargoState(page)).toHaveText('Свободен')

  await setSlider(page, 'gripperOpen', 80)
  await setSlider(page, 'gripperYaw', 60)
  await setSlider(page, 'ropeLength', 5.1)
  await waitForCrane(page)
  await setSlider(page, 'gripperOpen', 0)
  await expect(cargoHint(page)).toHaveText('Поверните захват вдоль ручки')
  await expect(cargoState(page)).toHaveText('Свободен')

  await setSlider(page, 'gripperYaw', 15)
  await setSlider(page, 'gripperOpen', 80)
  await waitForCrane(page)
  await expect(cargoHint(page)).toHaveText('Готов к захвату')
  await capture(page, 'before')
  const rope = page.locator('#ropeLength')
  const emptyLimit = Number(await rope.getAttribute('aria-valuemax'))
  await setSlider(page, 'gripperOpen', 0)
  await expect(cargoState(page)).toHaveText('Захвачен')
  expect(Number(await rope.getAttribute('aria-valuemax'))).toBeLessThan(emptyLimit)
  await setSlider(page, 'ropeLength', 3.6)
  await waitForCrane(page)
  await expect(cargoHint(page)).toHaveCount(0)

  await page.locator('#gripperOpen').fill('100')
  await expect(cargoHint(page)).toHaveText('Сначала опустите ящик на пол')
  await expect(page.locator('#gripperOpen')).toHaveValue('0')
  await expect(cargoState(page)).toHaveText('Захвачен')
  await capture(page, 'release-blocked')

  await setSlider(page, 'platformYaw', 54)
  await setSlider(page, 'boomPitch', 28)
  await setSlider(page, 'boomLength', 7.1)
  await setSlider(page, 'gripperYaw', 0)
  await waitForCrane(page)
  await expect(cargoState(page)).toHaveText('Захвачен')
  await expect(cargoHint(page)).toHaveCount(0)
  await capture(page, 'carrying')
  const carrying = await canvas(page).screenshot()
  await setSlider(page, 'sceneOrbit', 20)
  await expect.poll(async () => (await canvas(page).screenshot()).equals(carrying)).toBe(false)
  await page.getByRole('button', { name: 'Сбросить вид' }).click()
  await expect(cargoState(page)).toHaveText('Захвачен')
  await expect.poll(async () => (await canvas(page).screenshot()).equals(carrying)).toBe(true)
  const landingLimit = Number(await rope.getAttribute('aria-valuemax'))
  expect(landingLimit).toBeGreaterThan(4.1)
  expect(landingLimit).toBeLessThan(4.2)
  await expect(rope).toHaveAttribute('max', '8')
  const track = (await rope.boundingBox())!
  const trackY = track.y + track.height / 2
  await page.mouse.move(track.x + track.width * (3.6 - 0.5) / (8 - 0.5), trackY)
  await page.mouse.down()
  for (const fraction of [0.7, 0.95, 1.05]) {
    await page.mouse.move(track.x + track.width * fraction, trackY, { steps: 4 })
    await expect.poll(async () => Number(await rope.inputValue())).toBeCloseTo(landingLimit, 7)
  }
  await page.mouse.move(track.x + track.width * 0.35, trackY, { steps: 4 })
  expect(Number(await rope.inputValue())).toBeLessThan(landingLimit)
  await page.mouse.move(track.x + track.width * 0.97, trackY, { steps: 4 })
  await page.mouse.up()
  await expect.poll(async () => Number(await rope.inputValue())).toBeCloseTo(landingLimit, 7)
  await rope.press('ArrowLeft')
  await expect(rope).toHaveValue('4.1')
  await rope.press('ArrowRight')
  await expect.poll(async () => Number(await rope.inputValue())).toBeCloseTo(landingLimit, 7)
  await waitForCrane(page)
  await expect(cargoHint(page)).toHaveText('Можно открыть захват')
  await expect(status(page)).toContainText('Предел пола')
  await capture(page, 'rope-limit')
  await setSlider(page, 'gripperOpen', 80)
  await expect(cargoState(page)).toHaveText('На площадке')
  await waitForCrane(page)
  expect(Number(await rope.getAttribute('aria-valuemax'))).toBeGreaterThan(landingLimit)
  await expect(rope).toHaveAttribute('max', '8')
  await expect.poll(async () => Number(await rope.inputValue())).toBeCloseTo(landingLimit, 7)
  await setSlider(page, 'ropeLength', 3)
  await waitForCrane(page)
  await expect(cargoState(page)).toHaveText('На площадке')
  await capture(page, 'delivered')
  expect(errors).toEqual([])
})

test('G3 permits setting a crate on the floor outside the target', async ({ page }) => {
  await setSlider(page, 'ropeLength', 5.1)
  await expect(cargoHint(page)).toHaveText('Готов к захвату')
  await setSlider(page, 'gripperOpen', 0)
  await expect(cargoState(page)).toHaveText('Захвачен')
  await setSlider(page, 'ropeLength', 4.2)
  await waitForCrane(page)
  await setSlider(page, 'platformYaw', 16)
  await waitForCrane(page)
  await lowerRopeToLimit(page)
  await expect(cargoHint(page)).toHaveText('Можно открыть захват')
  await setSlider(page, 'gripperOpen', 80)
  await expect(cargoState(page)).toHaveText('Свободен')
  await waitForCrane(page)
  await expect(cargoHint(page)).toHaveText('Ящик поставлен вне площадки')
})

test('G3 stops the empty gripper above the lid, at the floor, and at a crate side', async ({ page }) => {
  const lidLimit = await lowerRopeToLimit(page)
  await waitForCrane(page)
  await expect(status(page)).toContainText('Крышка ящика')
  await expect(cargoState(page)).toHaveText('Свободен')
  await capture(page, 'crate-lid')
  await setSlider(page, 'ropeLength', 3.2)
  await setSlider(page, 'platformYaw', -18)
  await waitForCrane(page)
  const floorLimit = await lowerRopeToLimit(page)
  expect(floorLimit - lidLimit).toBeCloseTo(1.22, 5)
  await waitForCrane(page)
  await expect(status(page)).toContainText('Предел пола')
  await page.locator('#platformYaw').fill('25')
  await expect(status(page)).toHaveText('Поднимите захват над ящиком')
  await waitForCrane(page)
  await expect(page.locator('#platformYaw')).not.toHaveValue('25')
  await setSlider(page, 'ropeLength', 3.2)
  await waitForCrane(page)
  await setSlider(page, 'platformYaw', 25)
  await waitForCrane(page)
  await expect(page.locator('#platformYaw')).toHaveValue('25')
  await setSlider(page, 'ropeLength', 5.1)
  await expect(cargoHint(page)).toHaveText('Готов к захвату')
})
